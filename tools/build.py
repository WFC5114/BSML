#!/usr/bin/env python3
"""Builds js/i18n.js from the English text in the site and the translation
files in i18n/, and (with --preview) a single self-contained preview page.

  python3 tools/build.py            # refresh js/i18n.js, report missing keys
  python3 tools/build.py --preview  # also write dist/preview.html

English lives in the markup itself (data-t="key"), so editing the page and
re-running this script is enough to keep the dictionary in sync.
Traditional Chinese is generated from Simplified with OpenCC (Taiwan phrasing);
put any hand corrections in i18n/zh-hant-overrides.json.
"""
import base64, html, json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def english():
    en, clashes = {}, []
    page = (ROOT / 'index.html').read_text(encoding='utf-8')
    for m in re.finditer(r'data-t="([^"]+)"[^>]*>([^<]*)<', page):
        k, v = m.group(1), html.unescape(m.group(2)).strip()
        if k in en and en[k] != v:
            clashes.append((k, en[k], v))
        en.setdefault(k, v)
    for m in re.finditer(r'data-tp="([^"]+)"[^>]*placeholder="([^"]*)"', page):
        en.setdefault(m.group(1), m.group(2))
    for name in ('app.js', 'scene.js'):
        js = (ROOT / 'js' / name).read_text(encoding='utf-8')
        for m in re.finditer(r"""\bt\('([^']+)',\s*(['"])(.*?)\2\)""", js):
            en.setdefault(m.group(1), m.group(3).replace("\\'", "'"))
        for m in re.finditer(r"""\['(scene\.[a-z0-9]+)', '([^']*)'""", js):  # [key, English, ...] tables
            en.setdefault(m.group(1), m.group(2))
        for m in re.finditer(r"""'(toast\.[a-z]+)':\s*'([^']*)'""", js):
            en.setdefault(m.group(1), m.group(2))
        for m in re.finditer(r"""'data-t': '([^']+)'[^)]*\)[^;]*;\s*\w+\.textContent = '([^']*)'""", js):
            en.setdefault(m.group(1), m.group(2))
    for k, a, b in clashes:
        print(f'  ! key {k} has two English texts: "{a}" / "{b}"')
    return en


def main():
    en = english()
    zh = json.loads((ROOT / 'i18n/zh-hans.json').read_text(encoding='utf-8'))
    es = json.loads((ROOT / 'i18n/es.json').read_text(encoding='utf-8'))
    try:
        from opencc import OpenCC
    except ImportError:
        sys.exit('Install OpenCC first: python3 -m pip install opencc-python-reimplemented')
    cc = OpenCC('s2twp')
    hant = {k: cc.convert(v).replace('賬', '帳') for k, v in zh.items()}
    ov = ROOT / 'i18n/zh-hant-overrides.json'
    if ov.exists():
        hant.update(json.loads(ov.read_text(encoding='utf-8')))
    for name, d in (('zh-hans', zh), ('es', es)):
        missing = [k for k in en if k not in d]
        extra = [k for k in d if k not in en]
        print(f'{name}: {len(d)} strings, {len(missing)} missing, {len(extra)} unused')
        for k in missing:
            print(f'  missing {k}: {en[k]}')
        for k in extra:
            print(f'  unused {k}')
    data = {'en': en, 'zh-hans': zh, 'zh-hant': hant, 'es': es}
    out = '/* Generated by tools/build.py. Edit i18n/*.json or the page, then rebuild. */\n'
    out += 'window.BSML_I18N = ' + json.dumps(data, ensure_ascii=False, indent=0, sort_keys=True) + ';\n'
    (ROOT / 'js/i18n.js').write_text(out, encoding='utf-8')
    print(f'en: {len(en)} strings. Wrote js/i18n.js')
    if '--preview' in sys.argv:
        preview()


def preview():
    """One file with fonts, CSS and JS inlined, for sharing as a link."""
    css = (ROOT / 'css/site.css').read_text(encoding='utf-8')
    def font(m):
        b = (ROOT / 'assets/fonts' / m.group(1)).read_bytes()
        return 'url("data:font/woff2;base64,' + base64.b64encode(b).decode() + '")'
    css = re.sub(r'url\("\.\./assets/fonts/([^"]+)"\)', font, css)
    page = (ROOT / 'index.html').read_text(encoding='utf-8')
    body = page.split('<!--BUILD:BODY-START-->')[1].split('<!--BUILD:BODY-END-->')[0]
    js = ''.join((ROOT / 'js' / n).read_text(encoding='utf-8') + '\n' for n in ('i18n.js', 'scene.js', 'app.js'))
    out = ('<title>BSML Website Preview</title>\n<style>\n' + css + '\n</style>\n' + body +
           '\n<script>\n' + js.replace('</script', '<\\/script') + '</script>\n')
    d = ROOT / 'dist'
    d.mkdir(exist_ok=True)
    (d / 'preview.html').write_text(out, encoding='utf-8')
    print(f'Wrote dist/preview.html ({len(out)//1024} KB)')


if __name__ == '__main__':
    main()
